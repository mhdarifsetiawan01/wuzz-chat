'use strict';
const assert = require('assert');
const { state, loadFresh } = require('./_harness');
const loaded = loadFresh(['services/mediaCache.ts','services/mediaReceipt.ts']);
const cache = loaded.mediaCache.mediaCache;
const { acknowledgeCachedMedia: ack, resetMediaReceipts: reset } = loaded.mediaReceipt;
const url = 'https://media.wuzzhub.id/file.jpg';
const message = { id:'receipt-1', room_id:'dm-1', sender_id:'peer', content:'', media_url:url, file_size:100 };
const receiver = 'me';
let calls = 0, succeed = true;
const send = async () => { calls++; if(!succeed) throw new Error('Network failed'); };
(async()=>{
  state.fs.files.clear(); reset();
  await ack(message, receiver, send); assert.equal(calls,0,'mount without file must never ACK');
  const local = cache.getLocalFilePath(url,message.id);
  state.fs.files.set(local,{size:40});
  await ack(message,receiver,send);assert.equal(calls,0,'incomplete local file must never ACK');
  state.fs.files.set(local,{size:100});
  succeed=false;
  await assert.rejects(ack(message,receiver,send));assert.equal(calls,1);
  succeed=true;
  await Promise.all([ack(message,receiver,send),ack(message,receiver,send)]);
  assert.equal(calls,2,'retry success and simultaneous callers share one ACK');
  await ack(message,receiver,send);assert.equal(calls,2,'success deduplicated');
  reset();
  await ack({...message,sender_id:receiver},receiver,send);
  await ack({...message,room_id:'grp_1'},receiver,send);
  await ack({...message,room_id:'sub_1'},receiver,send);
  await ack({...message,media_status:'downloaded'},receiver,send);
  await ack(message,'',send);
  assert.equal(calls,2,'self/group/forum/already downloaded/no session do not ACK');
  await ack(message,receiver,send);assert.equal(calls,3,'new session can retry receipt');
  console.log('ACK: absent/incomplete/self/group/no-session skipped; failed ACK retry; concurrent and repeated dedup; session reset: OK');
})().catch(e=>{console.error(e);process.exitCode=1;});
