const assert = require('node:assert/strict');
const { loadFresh } = require('./_harness');
const { SourceRequest, SOURCE_UNAVAILABLE, hasSourceTarget, sourceContextPath } = loadFresh(['services/sourceMessage.ts']).sourceMessage;
const { sourceChatParams } = loadFresh(['services/sourceNavigation.ts']).sourceNavigation;
(async () => {
 const rows=[{id:'msg_source',room_id:'sub_forum'}];
 assert.equal(hasSourceTarget(rows,'sub_forum','msg_source'),true);
 for (const invalid of [[],[{...rows[0],is_deleted:true}],[{...rows[0],room_id:'sub_wrong'}]]) assert.equal(hasSourceTarget(invalid,'sub_forum','msg_source'),false);
 assert.equal(sourceContextPath('sub_forum','msg/source'),'/api/messages?room_id=sub_forum&message_id=msg%2Fsource');
 const target = sourceChatParams('grp_parent', 'Parent', 'sub_forum', 'msg_source', 'Ended forum');
 assert.equal(target.conversation.id, 'sub_forum');
 assert.equal(target.conversation.parent_id, 'grp_parent');
 assert.equal(target.sourceMessageId, 'msg_source');
 assert.equal(target.parentGroupConversation.id, 'grp_parent');
 assert.equal(sourceChatParams('grp_parent','Parent','grp_wrong','msg'), null);
 assert.equal(sourceChatParams('grp_parent','Parent','sub_forum',''), null);
 const request = new SourceRequest();
 assert.deepEqual(await request.run(async () => target), {value:target});
 for (const status of [403,404]) assert.deepEqual(await request.run(async()=>{throw {status}}), {error:SOURCE_UNAVAILABLE});
 assert.match((await request.run(async()=>{throw {status:500}})).error, /Periksa koneksi/);
 let finish, oldSignal;
 const old = request.run(signal=>{oldSignal=signal;return new Promise(r=>finish=r)});
 const latest = await request.run(async()=> 'new target');
 assert.equal(oldSignal.aborted,true); assert.equal(latest.value,'new target');
 finish('stale target'); assert.equal(await old,null);
 let reject;
 const canceled = request.run(()=>new Promise((_,r)=>reject=r));
 request.cancel(); reject(Error('late network error')); assert.equal(await canceled,null);
 let late;
 const timedOut = await request.run(()=>new Promise(r=>late=r),5);
 assert.match(timedOut.error,/Periksa koneksi/);late('too late');
 const account = request.run(()=>new Promise(r=>finish=r));request.cancel();finish('other account');assert.equal(await account,null);
 console.log('Source navigation, cancellation, replacement, unavailable and timeout passed');
})().catch(e=>{console.error(e);process.exitCode=1});
